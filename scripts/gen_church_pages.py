# ── sitemap ───────────────────────────────────────────────────────────────────

def update_sitemap(churches):
    path = ROOT / "sitemap.xml"
    xml = path.read_text(encoding="utf-8")
    if SITEMAP_MARK_START in xml:
        i = xml.index(SITEMAP_MARK_START)
        j = xml.index(SITEMAP_MARK_END) + len(SITEMAP_MARK_END)
        xml = xml[:i].rstrip() + "\n\n" + xml[j:].lstrip()
    entries = []
    for c in filter(has_schedule, churches):  # noindex pages stay out of the sitemap
        loc = f"{SITE}/nha-tho/{quote(c['url_slug'])}.html"
        entries.append(f"""  <url>
    <loc>{loc}</loc>
    <lastmod>{c["lastmod"]}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.6</priority>
  </url>""")
    block = SITEMAP_MARK_START + "\n" + "\n".join(entries) + "\n" + SITEMAP_MARK_END + "\n\n"
    xml = xml.replace("</urlset>", block + "</urlset>")
    path.write_text(xml, encoding="utf-8")


def main():
    churches = [clean(c) for c in json.loads((ROOT / "churches.json").read_text(encoding="utf-8"))]
    registry = json.loads(REGISTRY.read_text(encoding="utf-8")) if REGISTRY.exists() else {}
    churches = assign_slugs(churches, registry)
    update_registry(churches, registry)

    css, parts = load_template_parts()
    (ROOT / "assets" / "church.css").write_text(css.strip() + "\n" + EXTRA_CSS, encoding="utf-8")

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir()
    for c in churches:
        (OUT_DIR / f"{c['url_slug']}.html").write_text(church_page(c, parts), encoding="utf-8")

    update_sitemap(churches)
    written = len(list(OUT_DIR.glob("*.html")))
    assert written == len(churches), (written, len(churches))
    print(f"wrote {written} church pages, sitemap updated")


if __name__ == "__main__":
    main()
