OUT_DIR = ROOT / "nha-tho"
REGISTRY = ROOT / "scripts" / "church_pages.json"
PLAY_URL = "https://play.google.com/store/apps/details?id=com.buocchantheochua.app.prod"

# schedule.weekly keys follow the app: "0" = Chủ Nhật ... "6" = Thứ Bảy.
# Displayed Monday first, Sunday last.
# Every page lives in nha-tho/, so links are relative ("../assets/...") and work from file:// too;
# only canonical / og:url / sitemap use absolute SITE URLs.
DAYS = [("1", "Thứ Hai"), ("2", "Thứ Ba"), ("3", "Thứ Tư"), ("4", "Thứ Năm"),
        ("5", "Thứ Sáu"), ("6", "Thứ Bảy"), ("0", "Chủ Nhật")]

SITEMAP_MARK_START = "  <!-- church pages: generated by scripts/gen_church_pages.py -->"
SITEMAP_MARK_END = "  <!-- /church pages -->"

e = html.escape


def unsign(s):
    s = s.replace("đ", "d").replace("Đ", "D")
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def assign_slugs(churches, registry):
    """Unique URL slugs: slug -> slug-province -> +district -> +id prefix.

    Churches already in the registry keep their published slug; only new ids get one.
    """
    churches = sorted(churches, key=lambda c: c["id"])
    taken = {r["slug"] for r in registry.values()}
    for c in churches:
        if c["id"] in registry:
            c["url_slug"] = registry[c["id"]]["slug"]
    candidates = [
        lambda c: c["slug"],
        lambda c: f'{c["slug"]}-{unsign(c["province"])}',
        lambda c: f'{c["slug"]}-{unsign(c["district"])}-{unsign(c["province"])}',
        lambda c: f'{c["slug"]}-{unsign(c["district"])}-{unsign(c["province"])}-{c["id"][:8]}',
    ]
    pending = [c for c in churches if "url_slug" not in c]
    for level, make in enumerate(candidates):
        groups = defaultdict(list)
        for c in pending:
            groups[re.sub(r"-+", "-", make(c)).strip("-")].append(c)
        pending = []
        for slug, members in groups.items():
            last = level == len(candidates) - 1
            if (len(members) == 1 and slug not in taken) or last:
                for c in members:
                    c["url_slug"] = slug if not last or slug not in taken else f'{slug}-{c["id"]}'
                    taken.add(c["url_slug"])
            else:
                pending.extend(members)
    slugs = [c["url_slug"] for c in churches]
    assert len(slugs) == len(set(slugs)), "duplicate url slugs"
    return churches


def update_registry(churches, registry):
    """Record slugs and bump lastmod only for churches whose data changed."""
    today = date.today().isoformat()
    for c in churches:
        digest = hashlib.sha1(json.dumps({k: v for k, v in c.items() if k != "url_slug"},
                                         ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]
        prev = registry.get(c["id"])
        if not prev or prev["hash"] != digest:
            registry[c["id"]] = {"slug": c["url_slug"], "hash": digest, "lastmod": today}
        c["lastmod"] = registry[c["id"]]["lastmod"]
    REGISTRY.write_text(json.dumps(dict(sorted(registry.items())), ensure_ascii=False, indent=1) + "\n",
                        encoding="utf-8")


# Names that already say what kind of place it is; everything else is a parish ("Giáo xứ").
KIND_PREFIXES = ("giáo họ", "giáo xứ", "giáo điểm", "họ đạo", "chính tòa", "chính toà", "nhà thờ",
                 "nhà nguyện", "đền thánh", "tu viện", "đan viện", "trung tâm", "dòng ", "cộng đoàn",
                 "vương cung", "tiểu chủng")


PLACEHOLDER = "Chưa phân loại"  # backend's "unclassified district"; never show it


def clean(church):
    parts = [x.strip() for x in church["address"].split(",")]
    church["address"] = ", ".join(x for x in parts if x and x != PLACEHOLDER)
    if church["district"].strip() == PLACEHOLDER:
        church["district"] = ""
    return church


def full_name(church):
    """'Trinh Vương' -> 'Giáo xứ Trinh Vương', so searches like "giờ lễ giáo xứ trinh vương" match."""
    name = church["name"].strip()
    return name if name.lower().startswith(KIND_PREFIXES) else f"Giáo xứ {name}"


def times_for(church, key):
    raw = (church.get("schedule") or {}).get("weekly") or {}
    return sorted(t for t in raw.get(key) or [] if t)


def has_schedule(church):
    return any(times_for(church, k) for k, _ in DAYS)


def page_url(church):
    return f"{SITE}/nha-tho/{church['url_slug']}.html"


def maps_url(church):
    return f"https://www.google.com/maps/search/?api=1&query={church['latitude']},{church['longitude']}"


def describe(church):
    name, addr = full_name(church), church["address"]
    if name != church["name"]:
        name = f"{name} (nhà thờ {church['name']})"
    if has_schedule(church):
        sun = ", ".join(times_for(church, "0")) or "chưa cập nhật"
        week = ", ".join(times_for(church, "1")) or "chưa cập nhật"
        return (f"Giờ lễ {name}, {addr}. Chủ Nhật: {sun}. Ngày thường: {week}. "
                f"Xem lịch lễ cả tuần, chỉ đường và check-in đi lễ.")
    return f"Thông tin {name}, {addr}. Xem bản đồ chỉ đường và cập nhật giờ lễ trong ứng dụng Giờ Lễ & Lịch Công Giáo."


def json_ld(church):
    data = {
        "@context": "https://schema.org",
        "@type": "Church",
        "name": full_name(church),
        "alternateName": f"Nhà thờ {church['name']}",
        "url": page_url(church),
        "address": {
            "@type": "PostalAddress",
            "streetAddress": church["address"],
            "addressLocality": church["district"],
            "addressRegion": church["province"],
            "addressCountry": "VN",
        },
        "geo": {"@type": "GeoCoordinates", "latitude": church["latitude"], "longitude": church["longitude"]},
        "hasMap": maps_url(church),
    }
    if not church["district"]:
        del data["address"]["addressLocality"]
    if church.get("phone_number"):
        data["telephone"] = church["phone_number"]
    if church.get("photo"):
        data["image"] = church["photo"]
    crumbs = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Trang chủ", "item": f"{SITE}/"},
            {"@type": "ListItem", "position": 2, "name": full_name(church), "item": page_url(church)},
        ],
    }
    dump = lambda d: json.dumps(d, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return (f'<script type="application/ld+json">\n{dump(data)}\n</script>\n'
            f'<script type="application/ld+json">\n{dump(crumbs)}\n</script>')


# ── shared fragments ──────────────────────────────────────────────────────────

def load_template_parts():
    src = (ROOT / "index.html").read_text(encoding="utf-8")

    def between(start, end):
        i = src.index(start)
        j = src.index(end, i)
        return src[i:j + len(end)]

    css = between("<style>", "</style>")[len("<style>"):-len("</style>")]
    parts = {
        "hero_bg": between('<svg class="hero-bg"', "</svg>"),
        "logo": between('<svg viewBox="0 0 512 512"', "</svg>"),
        "phone": between('<div class="phone-wrap">', "</div>\n      </div>\n    </div>"),
        "features": between('<section class="features"', "</section>"),
        "how": between('<section class="how"', "</section>"),
        "script": between("<script>\n  (function", "</script>"),
    }
    # The phone-wrap slice ends one </div> past the phone-wrap itself; trim it back.
    parts["phone"] = parts["phone"][: parts["phone"].rindex("</div>")].rstrip()
    parts["phone"] = parts["phone"].replace('src="assets/', 'src="../assets/')
    return css, parts


